function langOf(lang) {
  return lang === 'zh' ? 'zh' : 'en';
}

/** Look a key up (language, then English, then the key itself) and fill {placeholders}; missing params become empty. */
export function t(key, lang, params) {
  const l = langOf(lang);
  const raw = STRINGS[l][key] !== undefined ? STRINGS[l][key] : STRINGS.en[key] !== undefined ? STRINGS.en[key] : key;
  return raw.replace(/\{(\w+)\}/g, (m, name) => {
    const v = params ? params[name] : undefined;
    return v === undefined || v === null ? '' : String(v);
  });
}

function techName(id, lang) {
  const key = 'technique.' + id;
  return STRINGS[langOf(lang)][key] !== undefined ? t(key, lang) : String(id);
}

function listText(items, lang) {
  const list = (Array.isArray(items) ? items : items === undefined || items === null ? [] : [items]).map((i) => techName(i, lang));
  return list.join(langOf(lang) === 'zh' ? '、' : ', ');
}

// Number text with at most one decimal and no trailing ".0" (66 -> "66", 2.34 -> "2.3").
function num(v) {
  const n = Number(v);
  return v === null || v === undefined || v === '' || !Number.isFinite(n) ? '' : String(+n.toFixed(1));
}

/** Sentence for an insight reason `{code, params}`; empty when there is no reason. */
export function reasonText(reason, lang) {
  if (!reason || !reason.code) return '';
  const params = reason.params || {};
  const known = STRINGS.en['reason.' + reason.code] !== undefined;
  if (!known) return t('reason.unknown', lang);
  if (reason.code === 'unscored_technique') {
    const names = listText(params.names, lang);
    return names ? t('reason.unscored_technique', lang, { names }) : t('reason.unscored_technique_plain', lang);
  }
  return t('reason.' + reason.code, lang, params);
}

/** {title, detail} for a finding `{code, severity, params}`. Unknown codes get a neutral placeholder. */
export function findingText(finding, lang) {
  const code = finding && finding.code;
  const p = (finding && finding.params) || {};
  if (!FINDING_CODES.includes(code)) {
    return { title: t('finding.unknown.title', lang), detail: t('finding.unknown.detail', lang) };
  }
  let titleKey = `finding.${code}.title`;
  const detailKey = `finding.${code}.detail`;
  const out = {};
  switch (code) {
    case 'technique_below_reference': {
      const gap = Number(p.lo) - Number(p.score);
      Object.assign(out, { technique: techName(p.technique, lang), score: num(p.score), lo: num(p.lo), gap: num(gap) });
      break;
    }
    case 'technique_strongest':
      Object.assign(out, { technique: techName(p.technique, lang), score: num(p.score) });
      break;
    case 'index_trend': {
      const d = Number(p.delta);
      const flat = !Number.isFinite(d) || Math.abs(d) < 0.05;
      titleKey = `finding.index_trend.title_${flat ? 'flat' : d > 0 ? 'up' : 'down'}`;
      const spanKey = 'range.span.' + p.range;
      Object.assign(out, {
        delta: num(Math.abs(d)),
        range: STRINGS.en[spanKey] !== undefined ? t(spanKey, lang) : String(p.range === undefined ? '' : p.range),
      });
      break;
    }
    case 'recovery_median':
      Object.assign(out, { sec: num(p.sec) });
      break;
    case 'techniques_unscored':
      Object.assign(out, { names: listText(p.names, lang) });
      break;
    case 'strokes_coverage_low':
      Object.assign(out, { classified: num(p.classified), total: num(p.total) });
      break;
    case 'rally_estimated': {
      const sigKey = 'signal.' + p.signal;
      Object.assign(out, { signal: STRINGS.en[sigKey] !== undefined ? t(sigKey, lang) : String(p.signal === undefined ? '' : p.signal) });
      break;
    }
    default:
      break;
  }
  return { title: t(titleKey, lang, out), detail: t(detailKey, lang, out) };
}
